LEAVE_TYPES = [
    ("Balance SL", "Sick Leave"),
    ("Balance CL", "Casual Leave"),
    ("Balance EL", "Earned Leave"),
]


def fix_doj(doj_str):
    parts = doj_str.split("-")
    y, m, d = int(parts[0]), int(parts[1]), int(parts[2])
    if m <= 12 and d <= 12:
        m, d = d, m
    return f"{y:04d}-{m:02d}-{d:02d}"


def execute():
    from frappe.utils import nowdate, getdate

    today = getdate(nowdate())
    created = 0
    skipped = 0
    not_found = []

    for emp_name, doj_str, sl, cl, el in EMPLOYEE_LEAVES:
        doj = getdate(fix_doj(doj_str))
        balances = {"Sick Leave": sl, "Casual Leave": cl, "Earned Leave": el}

        if sl == 0 and cl == 0 and el == 0:
            skipped += 1
            continue

        emp_name_search = emp_name.strip().upper().replace("(PAYAL)", "").strip()

        emp = frappe.db.get_value(
            "Employee",
            {
                "employee_name": ["like", f"%{emp_name_search}%"],
                "custom_is_support_staff": 1,
            },
            ["name", "employee_name", "status"],
            as_dict=True,
        )

        if not emp:
            emp = frappe.db.get_value(
                "Employee",
                {"employee_name": ["like", f"%{emp_name_search.split()[0]}%"], "custom_is_support_staff": 1},
                ["name", "employee_name", "status"],
                as_dict=True,
            )

        if not emp:
            emp = frappe.db.get_value(
                "Employee",
                {"date_of_joining": doj, "custom_is_support_staff": 1},
                ["name", "employee_name", "status"],
                as_dict=True,
            )

        if not emp:
            not_found.append(f"{emp_name} (DOJ: {doj})")
            print(f"NOT FOUND: {emp_name} (DOJ: {doj})")
            continue

        for db_col, lt_name in LEAVE_TYPES:
            bal = balances[lt_name]
            if bal <= 0:
                continue

            existing = frappe.db.exists(
                "Leave Allocation",
                {
                    "employee": emp.name,
                    "leave_type": lt_name,
                    "from_date": doj,
                    "to_date": "2026-12-31",
                    "docstatus": 1,
                },
            )
            if existing:
                print(f"SKIP (already allocated): {emp.employee_name} - {lt_name}")
                continue

            alloc = frappe.get_doc(
                {
                    "doctype": "Leave Allocation",
                    "employee": emp.name,
                    "leave_type": lt_name,
                    "from_date": doj,
                    "to_date": "2026-12-31",
                    "new_leaves_allocated": bal,
                    "carry_forward": 0,
                }
            )
            try:
                alloc.insert(ignore_permissions=True)
                alloc.submit()
                created += 1
                print(f"ALLOCATED: {emp.employee_name} - {lt_name} = {bal}")
            except Exception as e:
                if "OverlapError" in type(e).__name__:
                    print(f"SKIP (overlap): {emp.employee_name} - {lt_name}")
                else:
                    raise

    print(f"\nDone! Allocations created: {created}, Skipped (zero): {skipped}")
    if not_found:
        print(f"\nNot found ({len(not_found)}):")
        for n in not_found:
            print(f"  - {n}")
