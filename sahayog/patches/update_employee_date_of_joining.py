import frappe


def execute():
    from frappe.utils import getdate

    updated = 0
    not_found = []
    skipped = []

    data = get_data()

    for row in data:
        emp_name = row["name"].strip()
        new_doj = getdate(row["doj"])

        emp = frappe.db.get_value(
            "Employee",
            {"employee_name": emp_name, "custom_is_support_staff": 1},
            ["name", "employee_name", "date_of_joining"],
            as_dict=True,
        )

        if not emp:
            not_found.append(row["name"])
            print(f"NOT FOUND: {row['name']}")
            continue

        old_doj = emp.date_of_joining
        if old_doj and getdate(old_doj) == new_doj:
            print(f"UNCHANGED: {emp.employee_name} - DOJ already {new_doj}")
            continue

        frappe.db.set_value("Employee", emp.name, "date_of_joining", new_doj)
        updated += 1
        print(f"UPDATED: {emp.employee_name} - DOJ {old_doj} -> {new_doj}")

    print(f"\nDone! Updated: {updated}")
    if not_found:
        print(f"\nNot found ({len(not_found)}):")
        for n in not_found:
            print(f"  - {n}")
    frappe.db.commit()


